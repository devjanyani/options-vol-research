"""
Data provenance labels.

A core rule of this project: the user must always know what kind of data a
number came from. Every page and every stored row carries one of these labels.
"""

from __future__ import annotations

from enum import Enum


class DataKind(str, Enum):
    # Quotes downloaded right now from the market-data source.
    LIVE = "LIVE"
    # Real option-chain snapshots we downloaded on earlier days and stored.
    COLLECTED = "COLLECTED"
    # Prices produced by a model (e.g. Black-Scholes fed with VIX), NOT
    # real historical option quotes.
    MODELED = "MODELED"
    # Synthetic numbers used only by automated tests / UI smoke tests.
    SYNTHETIC = "SYNTHETIC"


DESCRIPTIONS = {
    DataKind.LIVE: "Current quotes from Yahoo Finance (may be delayed ~15 min, and stale outside market hours).",
    DataKind.COLLECTED: "Real option-chain snapshots this app downloaded on earlier days and stored in SQLite.",
    DataKind.MODELED: "Option prices computed with Black-Scholes from SPY prices and the VIX index. Not real historical option quotes.",
    DataKind.SYNTHETIC: "Synthetic test data generated by the developer test harness. NOT market data.",
}
